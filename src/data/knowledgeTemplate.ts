export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export async function downloadKnowledgeZip(
  files: Array<{ name: string; content: string; category?: string }> = []
) {
  const JSZip = (await import('jszip')).default;
  const zip = new JSZip();

  // Root templates
  zip.file('knowledge_template.txt', DEFAULT_KNOWLEDGE_TXT);
  zip.file('knowledge_template.md', DEFAULT_KNOWLEDGE_MD);
  zip.file('knowledge_template.json', DEFAULT_KNOWLEDGE_JSON);

  // Aggregated full files
  let mergedTxt = DEFAULT_KNOWLEDGE_TXT;
  let mergedMd = DEFAULT_KNOWLEDGE_MD;
  let mergedJson = DEFAULT_KNOWLEDGE_JSON;

  if (files.length > 0) {
    mergedTxt = files
      .map(
        (f) =>
          `====================================================================\nDOCUMENT: ${f.name} (Category: ${f.category || 'General'})\n====================================================================\n${f.content}\n`
      )
      .join('\n\n');

    mergedMd = files
      .map(
        (f) =>
          `# ${f.name}\n*Category: ${f.category || 'General'}*\n\n${f.content}\n\n---`
      )
      .join('\n\n');

    const jsonList = files.map((f) => {
      try {
        return {
          name: f.name,
          category: f.category || 'General',
          data: JSON.parse(f.content)
        };
      } catch (e) {
        return {
          name: f.name,
          category: f.category || 'General',
          content: f.content
        };
      }
    });
    mergedJson = JSON.stringify(jsonList, null, 2);

    // Individual backend knowledge documents in subfolder
    const kbFolder = zip.folder('knowledge_base_files');
    files.forEach((f) => {
      const sanitizedName = f.name.replace(/[^a-zA-Z0-9_.-]/g, '_');
      if (kbFolder) {
        kbFolder.file(sanitizedName, f.content);
      }
    });
  }

  zip.file('knowledge.txt', mergedTxt);
  zip.file('knowledge.md', mergedMd);
  zip.file('knowledge.json', mergedJson);

  const zipBlob = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(zipBlob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'tala_knowledge_base_bulk_export.zip';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
